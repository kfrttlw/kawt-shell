// the map for a name, or null
function get(name) {
    return icons[name] || null;
}

// wifi 0..100 % -> its map
function wifi(strength) {
    return "wifi" + Math.max(0, Math.min(4, Math.ceil(strength / 25)));
}

// 0..1, charging -> its map
function battery(level, charging) {
    return (charging ? "batc" : "bat") + Math.max(0, Math.min(10, Math.round(level * 10)));
}

// 0..1, muted -> vol0 (off), vol1, vol2
function volume(level, muted) {
    return muted || level <= 0 ? "vol0" : level < 0.5 ? "vol1" : "vol2";
}

// a radio button, drawn: a sunk round field (dark edge on the top and the left, light below and
// right), the dot when it's on
function radioMap(on) {
    var g = [];
    for (var y = 0; y < 16; y++) {
        var row = "";
        for (var x = 0; x < 16; x++) {
            var d = Math.sqrt((x + 0.5 - 8) * (x + 0.5 - 8) + (y + 0.5 - 8) * (y + 0.5 - 8));
            var upper = x + y < 15;
            var c = ".";
            if (d <= 6.2)
                c = d > 5.2 ? (upper ? "g" : "w") : d > 4.2 ? (upper ? "k" : "l") : on && d <= 2.2 ? "k" : "w";
            row += c;
        }
        g.push(row);
    }
    return g;
}
icons.radioOff = radioMap(false);
icons.radioOn = radioMap(true);

// a check box, drawn: a sunk square field, the tick when it's on
function boxMap(on) {
    var tick = {};
    for (var i = 0; i < 3; i++) {
        tick[(4 + i) + "," + (7 + i)] = 1;
        tick[(4 + i) + "," + (8 + i)] = 1;
    }
    for (var j = 0; j < 5; j++) {
        tick[(6 + j) + "," + (9 - j)] = 1;
        tick[(6 + j) + "," + (10 - j)] = 1;
    }
    var g = [];
    for (var y = 0; y < 16; y++) {
        var row = "";
        for (var x = 0; x < 16; x++) {
            var c = ".";
            if (x >= 1 && x <= 13 && y >= 1 && y <= 13) {
                if (x === 1 || y === 1)
                    c = x === 13 || y === 13 ? "w" : "g";
                else if (x === 13 || y === 13)
                    c = "w";
                else if (x === 2 || y === 2)
                    c = x === 12 || y === 12 ? "l" : "k";
                else if (x === 12 || y === 12)
                    c = "l";
                else
                    c = on && tick[x + "," + y] ? "k" : "w";
            }
            row += c;
        }
        g.push(row);
    }
    return g;
}
icons.boxOff = boxMap(false);
icons.boxOn = boxMap(true);
